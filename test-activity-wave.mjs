import assert from 'node:assert/strict';
import { createActivityWave } from './activity-wave.js';
const wave = createActivityWave();
const state = { session: 'one', turn: 1, running: true, label: '思考', calls: [], blocks: [] };
wave.update(1000, state);
assert.equal(wave.value(1190), 10, 'entering thinking produces a beat');
wave.update(2000, state);
assert.equal(wave.value(2190), 0, 'polling unchanged state does not produce beats');
state.label = '执行'; state.calls = [{ id: 'search-1' }];
wave.update(3000, state);
assert.equal(wave.value(3190), 10, 'query tool starts a beat');
state.calls = [{ id: 'search-1', progress: 20 }]; wave.update(3500, state);
assert.equal(wave.value(3690), 0, 'updating a tool does not restart its beat');
state.calls = [{ id: 'search-2' }]; wave.update(4000, state);
assert.equal(wave.value(4190), 10, 'consecutive tools in the same phase produce beats');
state.calls = []; state.label = '输出'; state.blocks = [{ kind: 'text', text: 'x'.repeat(127) }];
wave.update(5000, state);
assert.equal(wave.value(5190), 10, 'output phase begins a beat');
state.blocks[0].text += 'x'; wave.update(6000, state);
assert.equal(wave.value(6190), 10, '128 accumulated characters produce a beat');
wave.update(7000, state);
assert.equal(wave.value(7190), 0, 'unchanged text never pulses');
state.blocks[0].text += 'x'.repeat(1000); wave.update(8000, state, false);
assert.equal(wave.value(8190), 0, 'reduced motion clears pulses');
wave.update(8500, state);
assert.equal(wave.value(8690), 0, 'reenabling motion does not replay old output');
state.session = 'two'; state.running = false; state.label = '就绪'; wave.update(9000, state);
assert.equal(wave.value(6190), 0, 'switching sessions clears history');
state.running = true; state.label = '思考'; wave.update(10000, state);
wave.update(14601, state);
assert.equal(wave.value(10190), 0, 'expired pulses are discarded');
wave.reset(); assert.equal(wave.value(14190), 0);
console.log('Activity waveform tests passed.');

const toolsWave=createActivityWave();
const toolState={session:'tools',turn:1,step:1,running:true,label:'执行',calls:[],blocks:[]};
toolsWave.update(0,toolState);
toolState.blocks=[{kind:'tool-call',callId:'write-1',name:'write_file',argsRaw:''}];
toolsWave.update(1000,toolState);
assert.equal(toolsWave.value(1190),10,'streaming a write call triggers a beat');
toolState.blocks[0].argsRaw='x'.repeat(128);toolsWave.update(2000,toolState);
assert.equal(toolsWave.value(2190),10,'file content generation triggers progress beats');
toolState.blocks=[];toolState.calls=[{callId:'write-1'}];toolsWave.update(3000,toolState);
assert.equal(toolsWave.value(3190),0,'the same call is not replayed when execution begins');
toolState.completedCalls=[{callId:'edit-2'}];toolState.calls=[];toolState.running=false;toolState.label='就绪';toolsWave.update(4000,toolState);
assert.equal(toolsWave.value(4190),10,'fast completed edits between polls still pulse');
const tail=createActivityWave();const tailState={session:'tail',turn:1,running:true,label:'思考'};
tail.update(1000,tailState);
assert.equal(tail.bars(2300).length,40,'40 bars cover two seconds');
assert.deepEqual(tail.bars(2349),tail.bars(2300),'bars use stable 50ms slices');
const before=tail.bars(2300),after=tail.bars(2350);
assert.deepEqual(after.slice(0,-1),before.slice(1),'each tick moves every time slice exactly one bar left');
tail.update(3100,tailState);
assert.ok(tail.bars(3100)[0]>0,'pulse remains visible in the leftmost time slice after two seconds');
tailState.turn=2;tailState.running=false;tailState.label='就绪';tail.update(3200,tailState);
assert.ok(tail.bars(3200).some(x=>x>0),'new turns do not erase the outgoing pulse');
tail.update(3600,tailState);assert.ok(tail.bars(3600).every(x=>x===0),'the entire tail leaves the viewport before disappearing');

const waiting = createActivityWave();
const waitingState = { session: 'waiting', turn: 1, running: false, label: '等待' };
waiting.update(0, waitingState);
assert.equal(waiting.value(190), 7, 'pending user interaction starts a gentle heartbeat even when not running');
for (let time = 50; time <= 1600; time += 50) waiting.update(time, waitingState);
assert.equal(waiting.value(540), 5, 'the second beat is softer and follows after 350ms');
assert.equal(waiting.value(1000), 0, 'the double beat is followed by a quiet interval');
assert.equal(waiting.value(1790), 7, 'a new pair starts every 1600ms');
assert.equal(waiting.bars(1600).length, 40, 'waiting preserves the bar count');
assert.deepEqual(waiting.bars(1650).slice(0, -1), waiting.bars(1600).slice(1), 'waiting pulses also move one bar per 50ms');
waitingState.label = '思考'; waitingState.running = true;
waiting.update(1700, waitingState);
assert.equal(waiting.value(1890), 10, 'responding resumes the normal activity pulse');
waiting.update(1950, waitingState);
assert.equal(waiting.value(2190), 0, 'responding cancels the pending second waiting beat after the activity tail fades');
waitingState.label = '就绪'; waitingState.running = false;
waiting.update(3300, waitingState);
assert.equal(waiting.value(3490), 0, 'ordinary idle time does not create a waiting heartbeat');
waitingState.label = '等待'; waiting.update(4000, waitingState);
waiting.update(10000, waitingState);
assert.equal(waiting.value(10190), 7, 'returning from a hidden tab starts one fresh beat');
assert.equal(waiting.value(9190), 0, 'hidden time does not generate a backlog');
waiting.update(10350, waitingState, false);
assert.ok(waiting.bars(10350).every(value => value === 0), 'disabled motion clears waiting pulses');
waiting.update(12000, waitingState);
assert.equal(waiting.value(12190), 7, 'reenabling motion starts a fresh waiting pair');
waitingState.session = 'other'; waitingState.label = '就绪'; waiting.update(12100, waitingState);
assert.ok(waiting.bars(12100).every(value => value === 0), 'changing sessions clears waiting history and scheduling');
console.log('Waiting heartbeat tests passed.');

const approvalWave = createActivityWave();
const approvalState = { session: 'approval', turn: 1, label: '等待', running: false, waiting: 'approval' };
for (let time = 0; time <= 1200; time += 50) approvalWave.update(time, approvalState);
assert.equal(approvalWave.value(190), 7, 'approval keeps the gentle heartbeat strength');
assert.equal(approvalWave.value(490), 5, 'approval second beat follows after 300ms');
assert.equal(approvalWave.value(1390), 7, 'approval repeats after 1200ms instead of 1600ms');
approvalState.waiting = 'choice'; approvalWave.update(2000, approvalState);
for (let time = 2050; time <= 3600; time += 50) approvalWave.update(time, approvalState);
assert.equal(approvalWave.value(2540), 5, 'switching to a choice restores the softer 350ms spacing');
assert.equal(approvalWave.value(3390), 0, 'choice does not retain the faster approval cadence');
assert.equal(approvalWave.value(3790), 7, 'choice returns to the 1600ms cycle');
console.log('Approval heartbeat cadence tests passed.');
